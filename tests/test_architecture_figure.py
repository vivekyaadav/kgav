"""The architecture figures are generated, and this is what that bought.

WHY THIS FILE EXISTS. `arch.dot` and `arch_a4.dot` were drawn by hand on
2026-11-03 and nothing checked them. By 2026-11-20 they carried twelve
wrong items, and the user guide embedded them under "How the pieces fit
together" — presented as the current architecture, red boxes and all:

    nodes                78,789  ->  78,649
    edges               392,907  ->  396,223
    results files            28  ->  36
    stale results dirs   names results-corrected/ and results-prechange/,
                         neither of which exists
    train2021 variants        3  ->  4
    web/                 described a directory deleted on 2026-11-20
    defect: 0 PPI in train2021   -> it holds 11,744
    defect: CI ruff 281 findings -> ruff is pinned and lint is green
    defect: reach caveat never loads -> closed 2026-11-07
    inactive share          69%  ->  77.8%
    unreachable labelled    71%  ->  72.9%
    degree vs channels  0.62/0.58 -> 0.570/0.540

The file that preceded this one caught those up and then held the hand-
drawn figures to the repository, item by item. That is a check on a
hand-drawn file, not a reason for one: a human still had to edit twelve
boxes, and nothing could make the figure acquire a THIRTEENTH layer.

ON 2026-11-21 THE FIGURES BECAME GENERATED by
`scripts/write_architecture_figure.py`, from `kgav.pipeline.LAYERS`,
`kgav.assemble.LAYER_PRECEDENCE` and `MANIFEST.json`. What this file
checks therefore changed shape. It no longer asserts individual
figures — `--check` does that, and does it for every figure at once.
It asserts the three things a generator does not give you for free:

  * that the generator's own staleness check CAN fail (a check that
    cannot fail is worse than no check);
  * that the two editorial tables in the generator are COMPLETE, so a
    new ingest layer cannot be drawn as a nameless box or left out;
  * that the rendered A4 PDF still fits on one sheet of A4, which no
    amount of deriving the .dot can establish.
"""
from __future__ import annotations

import json
import re
import struct
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

FIGURES = ROOT / "doc2" / "figures"
ARCH = FIGURES / "arch.dot"
ARCH_A4 = FIGURES / "arch_a4.dot"
GENERATOR = ROOT / "scripts" / "write_architecture_figure.py"

from kgav.pipeline import LAYERS, release_dir                        # noqa: E402

RELEASE = release_dir(ROOT)

needs_release = pytest.mark.skipif(
    not (RELEASE / "edges.jsonl").exists(),
    reason="no assembled release on disk")

BOTH = pytest.mark.parametrize("dot", [ARCH, ARCH_A4],
                               ids=["arch.dot", "arch_a4.dot"])


def _digits(text: str) -> set[int]:
    """Every comma-grouped figure in the file, as integers."""
    return {int(m.group(0).replace(",", ""))
            for m in re.finditer(r"\b\d{1,3}(?:,\d{3})+\b", text)}


def _run(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(GENERATOR), *args],
                          cwd=ROOT, capture_output=True, text=True,
                          timeout=180)


# --------------------------------------------------------------- the files
@BOTH
def test_the_figure_exists(dot):
    assert dot.exists(), f"{dot.name} is gone"


@BOTH
def test_the_figure_says_it_is_generated(dot):
    """A reader who edits a generated file loses the edit on the next
    `make`, and the only warning they get is the one in the file."""
    head = dot.read_text().splitlines()[0]
    assert "GENERATED" in head and "Do not edit" in head, (
        f"{dot.name} does not open by saying it is generated: {head!r}")


@needs_release
def test_the_dot_files_are_current():
    """`make arch-figure-check`, run here so a stale figure fails a
    commit rather than a reader."""
    r = _run("--check")
    assert r.returncode == 0, r.stdout + r.stderr


@needs_release
def test_the_check_can_actually_fail(tmp_path):
    """A CHECK THAT CANNOT FAIL IS WORSE THAN NO CHECK — the defect this
    repository has shipped under four other names. Mutate one byte of
    the .dot, confirm --check reports it, and restore it."""
    original = ARCH_A4.read_text()
    try:
        ARCH_A4.write_text(original.replace("1 · INGEST", "1 · INGESTION", 1))
        r = _run("--check")
        assert r.returncode == 1, "a mutated .dot passed --check"
        assert "arch_a4.dot" in (r.stdout + r.stderr), (
            "--check does not name the file that moved")
    finally:
        ARCH_A4.write_text(original)
    assert _run("--check").returncode == 0, "the mutation was not restored"


# ------------------------------------------------------- what they contain
@BOTH
@needs_release
def test_the_release_counts_are_the_releases(dot):
    """Derived now, but asserted anyway: these two were the figures that
    sat wrong for seventeen days, and a generator reading the wrong
    manifest key would reproduce the defect silently."""
    manifest = json.loads((RELEASE / "MANIFEST.json").read_text())
    nodes = sum(manifest["nodes_by_class"].values())
    edges = sum(1 for line in (RELEASE / "edges.jsonl").read_text().splitlines()
                if line.strip())
    text = dot.read_text()
    assert f"{nodes:,} nodes" in text, (
        f"{dot.name} does not say {nodes:,} nodes")
    assert f"{edges:,} edges" in text, (
        f"{dot.name} does not say {edges:,} edges")
    for stale in (78789, 392907):
        assert stale not in _digits(text), (
            f"{dot.name} still carries the superseded figure {stale:,}")


@BOTH
def test_the_results_census_is_the_directory(dot):
    """'28 files' outlived eight more being written."""
    n = len(list((ROOT / "data" / "results").glob("*.json")))
    m = re.search(r"(\d+) stamped JSON artifacts", dot.read_text())
    assert m, f"{dot.name} no longer states a results count"
    assert int(m.group(1)) == n, (
        f"{dot.name} says {m.group(1)} results files; there are {n}")


@BOTH
def test_every_ingest_layer_is_drawn(dot):
    """THE FAILURE A HAND-DRAWN FIGURE CANNOT HAVE DETECTED. A new layer
    appears in `kgav.pipeline.LAYERS` and the picture has to acquire it."""
    text = dot.read_text()
    missing = [L.name for L in LAYERS if f"L_{L.name} " not in text]
    assert not missing, (
        f"{dot.name} draws no box for {missing}, which the pipeline declares")


@BOTH
@needs_release
def test_a_declared_layer_absent_from_the_release_is_drawn_as_absent(dot):
    """`curated` is declared and its raw directory is empty, so the
    flavivirus host factors it would supply are not in this graph.
    Drawing it like the others would state the opposite."""
    manifest = json.loads((RELEASE / "MANIFEST.json").read_text())
    absent = [L.name for L in LAYERS if L.name not in manifest["layers"]]
    text = dot.read_text()
    for name in absent:
        box = next((ln for ln in text.splitlines()
                    if ln.strip().startswith(f"L_{name} ")), "")
        assert "not in this release" in box, (
            f"{dot.name} draws {name} as if it were built; it is declared "
            f"and absent")
        assert "dashed" in box, (
            f"{dot.name} does not distinguish {name} visually")
    for name in (L.name for L in LAYERS if L.name in manifest["layers"]):
        box = next((ln for ln in text.splitlines()
                    if ln.strip().startswith(f"L_{name} ")), "")
        assert "not in this release" not in box, (
            f"{dot.name} marks {name} absent and the manifest has it")


@BOTH
def test_no_box_names_a_path_that_does_not_exist(dot):
    """A figure that draws a deleted component is worse than one with a
    stale number: the number is checkable by eye and the box is not."""
    text = dot.read_text()
    claimed = set()
    for m in re.finditer(r"\b((?:src|scripts|doc2|data|config|tests|web)/"
                         r"[A-Za-z0-9_./*{}-]*)", text):
        path = m.group(1).rstrip("/.,")
        # A GLOB OR A BRACE EXPANSION IS NOT A CLAIM. The measurement
        # cluster is labelled `src/kgav/{labels,baselines,...}.py`, and
        # `scripts/ingest_*.py` stands for nine files.
        if "*" in path or "{" in path:
            continue
        claimed.add(path)
    assert claimed, f"{dot.name} names no repository path at all"
    missing = sorted(p for p in claimed
                     if not (ROOT / p).exists()
                     and not (ROOT / (p + ".py")).exists())
    assert not missing, (
        f"{dot.name} draws {missing}, which this repository does not have")


@BOTH
def test_every_ingest_script_the_figure_implies_exists(dot):
    """The cluster header promises `scripts/ingest_*.py`, one per layer."""
    for L in LAYERS:
        assert (ROOT / "scripts" / L.script).exists(), (
            f"{L.name} declares {L.script}, which is not in scripts/")


def test_the_two_figures_draw_the_same_thing():
    """ONE TOPOLOGY, TWO PAGES. The hand-drawn pair disagreed: arch.dot
    carried seven red defect boxes and arch_a4.dot carried eight, three
    of them marked closed. Rendering both from one description is the
    repair, and this is the assertion that it held."""
    def ids(path: Path) -> set[str]:
        return set(re.findall(r"^\s{2,4}([A-Za-z_][A-Za-z0-9_]*) \[label=",
                              path.read_text(), re.MULTILINE))
    wide, a4 = ids(ARCH), ids(ARCH_A4)
    assert wide == a4, (
        f"the two figures draw different boxes: only in arch.dot "
        f"{sorted(wide - a4)}, only in arch_a4.dot {sorted(a4 - wide)}")


# ------------------------------------------- the generator's own guardrails
def test_a_layer_with_no_editorial_label_fails_the_generator(monkeypatch):
    """THE ONE FAILURE MODE A GENERATED FIGURE STILL HAS. The topology
    is derived, but the words on each box are written by a human. The
    tempting handling — fall back to the layer's name — draws a box that
    looks finished, so the generator raises instead. This is the test
    that the raise is reachable."""
    import write_architecture_figure as W

    monkeypatch.delitem(W.LAYER_GIVES, LAYERS[0].name)
    with pytest.raises(SystemExit) as e:
        W.topology()
    assert LAYERS[0].name in str(e.value)
    assert "LAYER_GIVES" in str(e.value)


def test_a_raw_directory_with_no_name_fails_the_generator(monkeypatch):
    """The same guard on the other table: a layer reading a directory
    nobody has named would otherwise be drawn with a path for a label."""
    import write_architecture_figure as W

    some_dir = next(d for L in LAYERS for d in W._raw_dirs(L))
    monkeypatch.delitem(W.RAW_SOURCE, some_dir)
    with pytest.raises(SystemExit) as e:
        W.topology()
    assert "RAW_SOURCE" in str(e.value)


def test_a_removed_layer_still_drawn_fails_the_generator(monkeypatch):
    """The guard in the other direction, which the first version did not
    have: a layer deleted from the pipeline but left in the editorial
    table would keep being drawn."""
    import write_architecture_figure as W

    monkeypatch.setitem(W.LAYER_GIVES, "a_layer_that_was_deleted", "x")
    with pytest.raises(SystemExit) as e:
        W.topology()
    assert "a_layer_that_was_deleted" in str(e.value)


def test_every_raw_directory_a_layer_reads_has_a_name():
    """Run forward rather than by mutation, so the table being complete
    is asserted and not merely assertable."""
    import write_architecture_figure as W

    needed = {d for L in LAYERS for d in W._raw_dirs(L)}
    assert needed, "no layer declares a raw input at all"
    assert not needed - set(W.RAW_SOURCE), (
        f"unnamed raw directories: {sorted(needed - set(W.RAW_SOURCE))}")
    assert not set(W.RAW_SOURCE) - needed, (
        f"RAW_SOURCE names directories no layer reads: "
        f"{sorted(set(W.RAW_SOURCE) - needed)}")


# ------------------------------------------------------- the printed pages
A4_PAGES = pytest.mark.parametrize(
    "stem", ["kgav_architecture_a4", "kgav_metagraph_a4"])


@A4_PAGES
def test_the_a4_pdf_is_one_page_that_fits_a4(stem):
    """The user guide promises "one page, fit to A4", and nothing checked
    it until 2026-11-20.

    graphviz adds about 0.2 inches of margin on top of -Gsize, so
    rendering with -Gsize=8.27,11.69 — A4 exactly — produces a page
    11.89in tall, which does not fit A4. A re-render during the
    2026-11-20 correction did exactly that. The flags live in the
    generator now, so the .dot a reader renders by hand is the one
    `make arch-figure` renders.
    """
    pdf = FIGURES / f"{stem}.pdf"
    assert pdf.exists(), f"{pdf.name} is gone"
    data = pdf.read_bytes()
    pages = data.count(b"/Type /Page") - data.count(b"/Type /Pages")
    assert pages == 1, f"{pdf.name} has {pages} pages; the guide says one"

    box = re.findall(rb"/MediaBox\s*\[([^\]]+)\]", data)
    assert box, f"{pdf.name} declares no MediaBox"
    n = [float(x) for x in box[0].split()]
    w, h = (n[2] - n[0]) / 72, (n[3] - n[1]) / 72
    assert w <= 8.27 and h <= 11.69, (
        f"{pdf.name} is {w:.2f} x {h:.2f} in and A4 is 8.27 x 11.69; it "
        f"would not print on one sheet without scaling")


@A4_PAGES
def test_the_a4_png_is_still_print_resolution(stem):
    """A careless re-render dropped the architecture PNG from 2480x3508
    to 930x1726. Both A4 pages are rendered at 300 dpi."""
    png = FIGURES / f"{stem}.png"
    assert png.exists(), f"{png.name} is gone"
    w, h = struct.unpack(">II", png.read_bytes()[16:24])
    assert w >= 2000, (
        f"{png.name} is {w}x{h}; at 300 dpi an A4 page is about 2480 wide, "
        f"so this has been re-rendered at screen resolution")
