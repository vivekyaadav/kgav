"""Every audited results file must have a step that regenerates it.

THE HOLE THIS CLOSES. `make check-results` globs data/results/*.json and
fails any file whose release stamp no longer matches the graph on disk.
The "Reproducing" block in docs/evaluation.md is what a reader runs to
clear that failure. Nothing connected the two, so a results file could
be -- and one was -- audited by check-results while no step in the block
rebuilt it: data/results/pathway_landscape.json, from the day it was
added until 2026-10-28.

That shape is silent in both directions. check-results reports the file
stale and the block, run top to bottom, leaves it stale; or the file is
regenerated by hand and happens to be current, which is what disguised
it here. The cost is the one this whole document is about -- a number
attributed to a graph that did not produce it.

So the block and the directory are checked against each other. A new
results file with no regeneration step fails here, which is the case
that cannot be caught by reading either file alone.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "evaluation.md"
RESULTS = ROOT / "data" / "results"

#: filename pattern -> the text that must appear in the reproduce block for
#: a file matching it to count as regenerated.
#:
#: Hand-maintained, and deliberately so: there is no way to derive "which
#: command writes this file" from the file itself for the generators that
#: record nothing, and a guard that silently covered only the ones that do
#: would be weakest exactly where the writers are oldest. The test below
#: fails on a results file matching no pattern, so the map cannot fall
#: behind the directory without saying so.
#: The four temporal files are listed separately rather than under one
#: `temporal_split.py` pattern. Under the shared pattern, deleting the
#: `--undated exclude` run still matched the three other invocations of the
#: same script, so the file it writes could go unregenerated with the guard
#: green -- which is the exact bug this module exists to catch, surviving
#: inside its own test.
WRITERS: list[tuple[str, str]] = [
    (r"^baselines_NCBITaxon_\d+\.json$", "scripts/run_baselines.py"),
    (r"^metapath_comparison\.json$", "scripts/compare_metapaths.py"),
    (r"^hard_negatives\.json$", "scripts/hard_negatives.py"),
    (r"^temporal_\d+_exclude\.json$", "--undated exclude"),
    (r"^temporal_\d+_computed_only\.json$", "--undated computed_only"),
    (r"^temporal_\d+_include\.json$", "--undated include"),
    (r"^temporal_\d+_include_overlap-keep\.json$", "--overlap-policy keep"),
    (r"^pathway_landscape\.json$", "make pathway-landscape"),
]


def block() -> str:
    """The fenced bash block under ## Reproducing."""
    text = DOC.read_text()
    assert "## Reproducing" in text, "the reproduce section was renamed"
    tail = text.split("## Reproducing", 1)[1]
    fences = tail.split("```")
    assert len(fences) >= 3, "the reproduce section has no fenced block"
    body = fences[1]
    assert body.lstrip().startswith("bash"), "the first fence is not bash"
    return body


def results_files() -> list[str]:
    return sorted(p.name for p in RESULTS.glob("*.json"))


def test_every_results_file_matches_a_known_writer():
    """The map cannot fall behind the directory.

    A results file nobody declared a writer for is the state this whole
    module exists to make loud: check-results will audit it, and no
    amount of running the block will refresh it.
    """
    unclaimed = [f for f in results_files()
                 if not any(re.match(pat, f) for pat, _ in WRITERS)]
    assert not unclaimed, (
        "these results files are audited by check-results but no entry in "
        "WRITERS says what regenerates them:\n  " + "\n  ".join(unclaimed))


@pytest.mark.parametrize("pattern,command", WRITERS,
                         ids=[p for p, _ in WRITERS])
def test_the_block_runs_the_writer_for_every_file_it_must_refresh(
        pattern, command):
    """Only for patterns that actually match something on disk: an entry
    for a results file this release does not produce is not a reason to
    require a step for it."""
    present = [f for f in results_files() if re.match(pattern, f)]
    if not present:
        pytest.skip(f"no file matches {pattern} in this release")
    # command_text(), not block(): a step commented out leaves its own
    # text behind, so matching the raw block accepted `# python
    # scripts/compare_metapaths.py` as a step that runs.
    assert command in command_text(), (
        f"{len(present)} file(s) matching {pattern} are audited by "
        f"check-results -- e.g. {present[0]} -- but the reproduce block "
        f"never runs {command!r}, so running it top to bottom leaves them "
        f"describing whatever graph they were last built from")


def expanded_block() -> str:
    """The block with every `make <target>` replaced by its recipe.

    A step may be a make target, and the Makefile is where that target's
    actual commands live: `make pathway-landscape` runs
    scripts/pathway_landscape.py, and matching the two by name alone
    fails on the hyphen the target uses and the underscore the script
    does. Resolving the recipe is the difference between asking whether
    the block mentions a script and asking whether it runs one.
    """
    makefile = (ROOT / "Makefile").read_text()
    recipes: dict[str, str] = {}
    current = None
    for line in makefile.splitlines():
        m = re.match(r"^([A-Za-z0-9_.-]+):(?!=)", line)
        if m:
            current = m.group(1)
            recipes.setdefault(current, "")
        elif current and line.startswith("\t"):
            recipes[current] += line + "\n"
        elif line and not line.startswith((" ", "\t")):
            current = None
    text = command_text()
    for target, recipe in recipes.items():
        text = text.replace(f"make {target}", recipe)
    return text


def test_a_make_target_in_the_block_resolves_to_a_real_recipe():
    """Guards the resolver itself. If the Makefile parser silently
    matched nothing, expanded_block() would equal block() and the test
    below would be checking the unexpanded text again."""
    assert "make pathway-landscape" in block()
    assert "make pathway-landscape" not in expanded_block()
    assert "pathway_landscape.py" in expanded_block()


def test_a_file_that_names_its_own_writer_is_checked_against_that_name():
    """The general version, for generators that record `measured_by`.

    It overlaps WRITERS on purpose. WRITERS is a human claim about what
    builds a file; `measured_by` is the file's own claim. When both
    exist they must agree with the block, and as more generators record
    it this test grows while WRITERS stays a fallback.
    """
    checked = 0
    text = expanded_block()
    for p in sorted(RESULTS.glob("*.json")):
        d = json.loads(p.read_text())
        script = d.get("measured_by") or d.get("provenance", {}).get(
            "measured_by")
        if not script:
            continue
        checked += 1
        stem = Path(script).stem
        assert stem in text, (
            f"{p.name} records measured_by={script!r} and the reproduce "
            f"block never mentions {stem}")
    assert checked, "no results file records measured_by; this test is vacuous"


def commands() -> list[str]:
    """The block's command lines, comments and blank lines removed.

    Not a split on the text: `make check-results` is named in the block's
    own header comment, so splitting on the string put the whole block
    after it and the first version of the test below passed on any input.
    """
    out = []
    for raw in block().splitlines():
        # Trailing comments too, not only whole-comment lines: several
        # steps carry one ("# LAST: the split the rest reads"), and a
        # check for "is this step disabled" that leaves those in place
        # is reading commentary as command.
        line = re.sub(r"\s+#.*$", "", raw).strip()
        if not line or line.startswith("#") or line == "bash":
            continue
        if out and out[-1].endswith("\\"):      # continuation of the last
            out[-1] = out[-1][:-1].rstrip() + " " + line
        else:
            out.append(line)
    return out


def command_text() -> str:
    """The block's commands as one string, comments removed.

    Every "is this step present" check reads this rather than the raw
    block, because the raw block contains the text of a step that has
    been commented out.
    """
    return "\n".join(commands())


def test_a_commented_out_step_does_not_count_as_a_step():
    """Guards the distinction above. If commands() ever stopped stripping
    comments, every presence check in this file would quietly go back to
    accepting a disabled step."""
    assert "#" not in command_text()
    assert "compare_metapaths" in command_text()


#: script -> the flag that must appear in its LAST invocation.
#:
#: Several steps run the same script repeatedly into one output, so the
#: last run is the one whose numbers survive. The block says so twice,
#: in both cases because it had been wrong: hard_negatives.py row 5 used
#: to run first and the no-op control overwrote it, leaving
#: hard_negatives.json holding row 2 while the document read it as row 5.
#: Ordering is not something a reader can verify by looking.
#: (script, flag that must be in the last WRITING run, flags marking a run
#: that writes nothing and so cannot be the one that stays on disk).
#:
#: The third element is not defensive padding. temporal_split.py's final
#: invocation in the block is the --overlap-policy keep control, which the
#: block itself says "writes no split, so it cannot disturb the one
#: above" -- and that control's command line also contains `--undated
#: include`. Checking the last command therefore passed while the real
#: last split was something else entirely, which is the ordering bug this
#: entry exists to catch, hiding inside the check for it.
LAST_RUN_WINS: list[tuple[str, str, tuple[str, ...]]] = [
    ("scripts/hard_negatives.py",
     "--label-source infores:ncats-opendata", ()),
    ("scripts/temporal_split.py",
     "--undated include", ("--overlap-policy keep",)),
]


@pytest.mark.parametrize("script,flag,controls", LAST_RUN_WINS,
                         ids=[s for s, _, _ in LAST_RUN_WINS])
def test_the_run_that_stays_on_disk_is_the_one_the_document_quotes(
        script, flag, controls):
    runs = [c for c in commands() if script in c]
    if not runs:
        pytest.skip(f"{script} is not in the block")
    writing = [c for c in runs if not any(x in c for x in controls)]
    assert len(writing) > 1, (
        f"{script} has {len(writing)} writing run(s), so this entry orders "
        f"nothing -- drop it rather than leave a test that cannot fail")
    assert flag in writing[-1], (
        f"the last writing {script} run is {writing[-1]!r}, so the file "
        f"left on disk is not the one carrying {flag!r} that the document "
        f"quotes")


def test_check_results_is_the_last_command():
    """It is the audit of everything above it. A block that runs it in the
    middle certifies files that later steps then overwrite."""
    cmds = commands()
    assert cmds, "no commands parsed out of the reproduce block"
    assert cmds[-1] == "make check-results", (
        f"the last command is {cmds[-1]!r}, so check-results is not "
        f"auditing everything the block writes")
    assert sum(c == "make check-results" for c in cmds) == 1
